for (const q of [...survey.core, ...Object.values(survey.branches).flatMap(b => b.questions), ...survey.closing]) {
  english[q.label] = englishQuestions[q.id][0];
}
let language = 'en';
export function setLanguage(value) { language = value === 'ro' ? 'ro' : 'en'; }
const pattern = new RegExp(Object.keys(english).sort((a,b) => b.length-a.length).map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
export function t(text) { return language === 'ro' ? text : String(text).replace(pattern, key => english[key]); }
export function html(strings, ...values) { return strings.reduce((out, part, i) => out + t(part) + (i < values.length ? values[i] : ''), ''); }
